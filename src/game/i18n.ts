const TABLES: Record<Lang, Record<string, string>> = { ko: KO, en: EN };

export function t(lang: Lang, key: string, vars?: Vars) {
  let s = TABLES[lang][key] ?? TABLES.ko[key] ?? key;
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
  }
  return s;
}

export function readSavedLang(): Lang {
  if (typeof window === "undefined") return "ko";
  try {
    return window.localStorage.getItem("n2-lang") === "en" ? "en" : "ko";
  } catch {
    return "ko";
  }
}

export function persistLang(lang: Lang) {
  try {
    window.localStorage.setItem("n2-lang", lang);
  } catch {
    /* ignore */
  }
  if (typeof document !== "undefined") {
    document.documentElement.lang = lang === "en" ? "en" : "ko";
    document.title = t(lang, "app.name");
  }
}
